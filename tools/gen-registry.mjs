// Writes content/registry.ts from the lesson folders under content/public.
// A folder is registered only when lesson.ts and all three language files exist,
// so a lesson that is still being written never breaks the build.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..", "content");
const pub = join(root, "public");
const langs = ["uz", "ru", "en"];

const slugs = readdirSync(pub, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .filter((s) => ["lesson", ...langs].every((f) => existsSync(join(pub, s, `${f}.ts`))))
  .sort();

const camel = (slug) => slug.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const name = (slug, suffix) => `${camel(slug)}${suffix}`;
const cap = (l) => l[0].toUpperCase() + l.slice(1);

const lines = [
  "// Generated by tools/gen-registry.mjs. Do not edit by hand.",
  'import type { LessonEntry } from "./types";',
  ...slugs.flatMap((s) => [
    `import ${name(s, "Lesson")} from "./public/${s}/lesson";`,
    ...langs.map((l) => `import ${name(s, cap(l))} from "./public/${s}/${l}";`),
  ]),
  "",
  "export const registry: Record<string, LessonEntry> = {",
  ...slugs.map(
    (s) =>
      `  ${JSON.stringify(s)}: { lesson: ${name(s, "Lesson")}, text: { uz: ${name(s, "Uz")}, ru: ${name(s, "Ru")}, en: ${name(s, "En")} } },`,
  ),
  "};",
  "",
];

const out = join(root, "registry.ts");
const next = lines.join("\n");
if (!existsSync(out) || readFileSync(out, "utf8") !== next) writeFileSync(out, next);
console.log(`registry: ${slugs.length} lessons`);
